/**
 * Rendering the eval's findings into `docs/eval-results.md`.
 *
 * The harness owns a marker-delimited region of that file and rewrites it in
 * place. Everything outside the markers is hand-written analysis — why a change
 * was made, what a gap means — which no harness can produce. Everything inside
 * is computed, so no number in the results doc is ever hand-transcribed and
 * able to drift from the run that produced it.
 */
import type { Metrics } from './pairwise';
import { zeroEventUpperBound } from './pairwise';
import type { PublishedRun } from './history';
import type { AttachCounts, Cell, CeilingRow, Overlap, Relation, Selection, Thresholds } from './sweep';

export const BEGIN = '<!-- eval:begin — generated by `npm run eval`; edits inside are overwritten -->';
export const END = '<!-- eval:end -->';

export type ReportData = {
  date: string;
  provider: string;
  apiCalls: number;
  promptVersions: Record<string, string>;
  fixturesRecordedAt: string | null;
  requests: number;
  labelledProblems: number;
  truePairs: number;
  totalPairs: number;
  degradedStages: Record<string, number>;
  configured: Thresholds & { basis: string };
  cells: Cell[];
  selection: Selection;
  current: { thresholds: Thresholds; all: Metrics; auto: Metrics; counts: AttachCounts };
  planted: { grouped: number; total: number; missed: string[] };
  relatedPairs: { merged: number; total: number; mergedPairs: string[] };
  ceiling: CeilingRow[];
  overlap: Overlap;
  binding: ReturnType<typeof import('./sweep').bindingSignal>;
  verdictMix: Record<Relation, number>;
  history: PublishedRun;
  grid: readonly number[];
  floor: { metric: number | null; limit: number; passed: boolean };
};

const n3 = (v: number | null | undefined) => (v === null || v === undefined ? '—' : v.toFixed(3));
const n2 = (v: number | null | undefined) => (v === null || v === undefined ? '—' : v.toFixed(2));
const pct = (v: number | null | undefined) =>
  v === null || v === undefined ? '—' : `${(v * 100).toFixed(0)}%`;
const arrow = (now: number, before: number) => (now > before ? '↑' : now < before ? '↓' : '—');

/** The full confusion matrix, true negatives included. */
const cm = (m: Metrics) => `${m.tp} / ${m.fp} / ${m.fn} / ${m.tn}`;

export function renderReport(d: ReportData): string {
  const degraded = Object.values(d.degradedStages).reduce((a, b) => a + b, 0);
  const sel = d.selection;
  const chosen = sel.chosen;
  const atZeroAsk = d.cells.filter((c) => c.tAsk === d.grid[0]).sort((a, b) => a.tAuto - b.tAuto);
  const bound = zeroEventUpperBound(d.current.counts.attached);

  return [
    BEGIN,
    '',
    `## ${d.date} — Threshold sweep and current metrics (C7)`,
    '',
    'Everything in this section is **generated by `npm run eval`**. Nothing here is',
    'hand-typed, so no figure can drift from the run that produced it. The analysis',
    'sections above and below are hand-written; the numbers are not.',
    '',
    '### How this run was produced',
    '',
    `| | |`,
    `|---|---|`,
    `| provider | \`${d.provider}\` — **${d.apiCalls} API calls**, \`fetch\` disabled in-process |`,
    `| corpus | ${d.requests} seeded requests, ${d.labelledProblems} labelled problems |`,
    `| prompts | ${Object.entries(d.promptVersions)
      .map(([k, v]) => `${k} \`${v}\``)
      .join(' · ')} |`,
    `| fixtures recorded | ${d.fixturesRecordedAt ?? 'no manifest'} |`,
    `| degraded stages | ${degraded} — a non-zero count means stale fixtures, and fails the run |`,
    `| metric | pairwise over ${d.totalPairs} request pairs; ${d.truePairs} of them are true duplicates |`,
    '',
    'The pipeline is re-run end to end from fixtures into a throwaway in-memory',
    'database, so the measurement neither depends on nor disturbs `data/fis.db`.',
    'The sweep then replays **stage 5 only**, over the exhaustively recorded',
    '`(request, candidate, verdict, confidence, similarity)` tuples.',
    '',
    `### Current build at the configured thresholds (T_ask ${n2(d.configured.tAsk)}, T_auto ${n2(d.configured.tAuto)})`,
    '',
    '| band | precision | recall | F1 | tp / fp / fn / tn |',
    '|---|---|---|---|---|',
    `| all bands | **${n3(d.current.all.precision)}** | **${n3(d.current.all.recall)}** | ${n3(d.current.all.f1)} | ${cm(d.current.all)} |`,
    `| auto band only | **${n3(d.current.auto.precision)}** | ${n3(d.current.auto.recall)} | ${n3(d.current.auto.f1)} | ${cm(d.current.auto)} |`,
    '',
    `Problems formed: **${d.current.counts.problems}** against a ground truth of ${d.labelledProblems}. ` +
      `${d.current.counts.attached} requests attached (${d.current.counts.auto} auto, ` +
      `${d.current.counts.flagged} flagged for a PM — ${pct(d.current.counts.reviewLoad)} review load), ` +
      `${d.current.counts.created} formed a new problem.`,
    '',
    `Planted disjoint pairs caught: **${d.planted.grouped}/${d.planted.total}**` +
      (d.planted.missed.length ? ` (missed ${d.planted.missed.join(', ')})` : '') +
      `. Related-but-distinct pairs wrongly merged: **${d.relatedPairs.merged}/${d.relatedPairs.total}**` +
      (d.relatedPairs.mergedPairs.length ? ` (${d.relatedPairs.mergedPairs.join(', ')})` : '') +
      '.',
    '',
    `Verdict mix across all ${Object.values(d.verdictMix).reduce((a, b) => a + b, 0)} recorded tuples: ` +
      `${d.verdictMix.same} \`same\`, ${d.verdictMix.related} \`related\`, ${d.verdictMix.distinct} \`distinct\`.`,
    '',
    '> **Band denominators.** Both rows above are scored on the same',
    `> ${d.truePairs} true pairs. Earlier hand-computed auto-band recall in this file`,
    '> divided an auto-band numerator by an all-band denominator, which inflates it;',
    '> the harness does not.',
    '',
    '### v1 → v2, all-band',
    '',
    `| metric | ${d.history.label} (\`${d.history.adjudicationPrompt}\`) | current (\`${d.promptVersions.adjudicate}\`) | |`,
    '|---|---|---|---|',
    `| precision | ${n3(d.history.precision)} | **${n3(d.current.all.precision)}** | ${arrow(d.current.all.precision ?? 0, d.history.precision)} |`,
    `| recall | ${n3(d.history.recall)} | **${n3(d.current.all.recall)}** | ${arrow(d.current.all.recall, d.history.recall)} |`,
    `| true merges (tp) | ${d.history.tp} | **${d.current.all.tp}** | ${arrow(d.current.all.tp, d.history.tp)} |`,
    `| false merges (fp) | ${d.history.fp} | **${d.current.all.fp}** | ${arrow(d.current.all.fp, d.history.fp)} |`,
    `| problems formed (truth ${d.labelledProblems}) | ${d.history.problems} | **${d.current.counts.problems}** | ${arrow(d.current.counts.problems, d.history.problems)} |`,
    `| planted pairs caught | ${d.history.plantedPairsCaught}/${d.planted.total} | **${d.planted.grouped}/${d.planted.total}** | ${arrow(d.planted.grouped, d.history.plantedPairsCaught)} |`,
    `| related pairs merged | ${d.history.relatedPairsMerged}/${d.relatedPairs.total} | **${d.relatedPairs.merged}/${d.relatedPairs.total}** | ${arrow(d.relatedPairs.merged, d.history.relatedPairsMerged)} |`,
    '',
    `v1's figures are **quoted from its published run**, not recomputed: a fixture key`,
    `includes the prompt's content hash, so reproducing them means reverting`,
    '`prompts/adjudicate.md`. See `src/eval/history.ts` for the provenance.',
    '',
    '### Stage-1 recall ceiling, reported separately',
    '',
    'ADR 0002 requires this to be separate from end-to-end precision, so a',
    'retrieval ceiling is never misread as an adjudication failure. For each true',
    'pair, could retrieval put the earlier request’s problem in front of the',
    'adjudicator at all?',
    '',
    '| retrieval breadth | pairs reachable | ceiling |',
    '|---|---|---|',
    ...d.ceiling.map(
      (r) =>
        `| ${r.k === 'all' ? '**all problems** (shipped)' : `top-${r.k}`} | ${r.available}/${r.total} | ${n3(r.share)} |`,
    ),
    '',
    'The shipped breadth imposes **no ceiling at all**, which is the point of',
    "`candidateLimit: \"all\"`: every miss below is adjudication's, not retrieval's.",
    "The top-*k* rows hold this run's formation fixed and are the measured input to",
    "[ADR 0003](./adr/0003-brute-force-cosine.md)'s breadth trigger — the cost of",
    'narrowing retrieval when the adjudication prompt stops fitting the problem count.',
    '',
    '### Which signal `T_auto` actually tests',
    '',
    `\`autoScore\` is \`min(confidence, similarity)\`. Across all ${d.binding.sameVerdicts} \`same\` verdicts, ` +
      `similarity is the binding term **${d.binding.similarityBinds} times** and confidence ` +
      `**${d.binding.confidenceBinds}**: confidence ranges ` +
      `${n3(d.binding.minConfidence)}–${n3(d.binding.maxConfidence)} while similarity ranges ` +
      `${n3(d.binding.minSimilarity)}–${n3(d.binding.maxSimilarity)}, so the minimum is ` +
      `${d.binding.confidenceBinds === 0 ? '**always**' : 'usually'} the cosine.`,
    '',
    `\`T_auto\` is therefore a cosine cut in disguise, and the scores it cuts ` +
      `(${n3(d.binding.minScore)}–${n3(d.binding.maxScore)}) straddle the band C2 measured as`,
    'unseparable — worst true duplicate 0.741 below best adjacent-but-distinct',
    '0.772. That is a structural reason this corpus cannot calibrate `T_auto` by',
    'similarity, independent of the sweep below: the threshold is being asked to',
    'discriminate using the one signal already measured as unable to.',
    '',
    `C2 measured that overlap over 14 hand-picked request pairs. Every one of the`,
    `${d.overlap.n} recorded tuples is a (request, problem) comparison whose ground truth`,
    `is known, so it can be remeasured over all of them — at the level \`T_auto\``,
    'actually operates on:',
    '',
    '| cosine between a request and… | min | max |',
    '|---|---|---|',
    `| …a problem genuinely its own | **${n3(d.overlap.sameMin)}** | ${n3(d.overlap.sameMax)} |`,
    `| …a problem from another true cluster | ${n3(d.overlap.diffMin)} | **${n3(d.overlap.diffMax)}** |`,
    '',
    `Separation: **${n3(d.overlap.separation)}** — the classes overlap at problem level too.`,
    `This gives the one constraint the corpus *does* place on \`T_auto\`: above`,
    `**${n3(d.overlap.contestedAbove)}**, no auto-attach can land at a cosine where a known`,
    'non-duplicate also sits. Below it, the system would be acting unattended',
    'inside the band where cosine is demonstrably uninformative. The',
    'pre-registered rule contains no such clause — it is reported here because it',
    'is measured, and it is why the adopted value is the lowest grid point above',
    'that line rather than the lowest grid point overall.',
    '',
    `### The sweep — every (T_ask, T_auto) pair on the grid`,
    '',
    `Grid: ${d.grid.map((g) => n2(g)).join(', ')}. Cells with \`T_ask > T_auto\` are omitted:`,
    'they would auto-attach below the floor at which anything is asked.',
    '',
    '| T_ask | T_auto | all: P | all: R | all tp/fp/fn/tn | auto: P | auto: R | auto tp/fp/fn/tn | problems | flagged | blind spot |',
    '|---|---|---|---|---|---|---|---|---|---|---|',
    ...d.cells
      .slice()
      .sort((a, b) => a.tAsk - b.tAsk || a.tAuto - b.tAuto)
      .map(
        (c) =>
          `| ${n2(c.tAsk)} | ${n2(c.tAuto)} | ${n3(c.all.precision)} | ${n3(c.all.recall)} | ${cm(c.all)} ` +
          `| ${n3(c.auto.precision)} | ${n3(c.auto.recall)} | ${cm(c.auto)} | ${c.counts.problems} ` +
          `| ${c.counts.flagged} | ${c.blindSpot === 0 ? 'exact' : `${c.blindSpot} unseen`} |`,
      ),
    '',
    '**`T_auto` rows are exact.** Under formation-by-verdict it moves an attach',
    'between the auto and flagged bands and never changes which problems exist, so',
    'each row is behaviour the system would really have.',
    '',
    '**`T_ask` rows above 0 are counterfactual, and the "blind spot" column prices',
    'the approximation.** `resolve()` has no `T_ask` parameter: formation follows the',
    "adjudicator's verdict, per [ADR 0002](./adr/0002-two-stage-dedupe.md)'s amendment.",
    'Raising it can only turn an attach into a new problem, so every problem the',
    'canonical pass formed still exists and every recorded verdict still applies —',
    'but the *extra* problems were never offered to the requests that arrived after',
    'them, and that count is the blind spot. At `T_ask = 0` it is zero and the sweep',
    'is exact.',
    '',
    '### What `T_auto` costs and buys',
    '',
    `At \`T_ask ${n2(d.grid[0])}\`, the only axis \`T_auto\` moves is how much of the work a`,
    'human is asked to confirm:',
    '',
    '| T_auto | auto attaches | flagged | review load | auto-band precision | auto-band recall |',
    '|---|---|---|---|---|---|',
    ...atZeroAsk.map(
      (c) =>
        `| ${n2(c.tAuto)} | ${c.counts.auto} | ${c.counts.flagged} | ${pct(c.counts.reviewLoad)} ` +
        `| ${n3(c.auto.precision)} | ${n3(c.auto.recall)} |`,
    ),
    '',
    '### The selection rule, applied',
    '',
    'Fixed in advance ([ARCHITECTURE](./ARCHITECTURE.md#choosing-thresholds-from-the-eval)):',
    `**the lowest \`T_auto\` whose auto-merge precision ≥ ${n2(sel.rule.minAutoPrecision)}, then the`,
    `lowest \`T_ask\` keeping recall ≥ ${n2(sel.rule.minRecall)}.** A \`T_auto\` is judged at the`,
    'lowest `T_ask`, which is the most permissive formation and so the hardest',
    'precision test it faces.',
    '',
    chosen
      ? `**Literal output of the rule: \`T_ask ${n2(chosen.tAsk)}\`, \`T_auto ${n2(chosen.tAuto)}\`.**`
      : '**The rule selected nothing: no cell on the grid clears the precision floor.**',
    '',
    '| constraint | status |',
    '|---|---|',
    `| auto-merge precision ≥ ${n2(sel.rule.minAutoPrecision)} | ${
      sel.precisionNonBinding
        ? '**non-binding** — every cell on the grid clears it, so it selected nothing'
        : 'binding'
    } |`,
    `| recall ≥ ${n2(sel.rule.minRecall)} | ${
      sel.recallUnsatisfiable
        ? `**unsatisfiable** — the best recall anywhere on the grid is ${n3(sel.bestRecall)}`
        : 'met'
    } |`,
    '',
    'A `—` in an auto-band precision column is an **empty auto band**, not a',
    'failure: a `T_auto` above every recorded score auto-attaches nothing, so',
    'precision there is undefined. Those cells are excluded from the constraint',
    'rather than counted as breaches, which is what makes the verdict above honest.',
    '',
    sel.precisionNonBinding
      ? [
          'Both clauses failed to bite, which is itself this run\'s principal finding about',
          'the *rule*. It was written expecting precision to decay as `T_auto` falls. It',
          `does not: the adjudicator makes **${d.current.all.fp} false merges anywhere in the corpus**, so`,
          'every operating point has precision 1.000 and "the lowest `T_auto` that keeps',
          'precision" degenerates to the lowest value on the grid — i.e. ask no human at all,',
          'which is the posture [ADR 0005](./adr/0005-duplicate-resolution-actor.md) exists to reject.',
          '',
          `The sample says why the rule cannot do better here. Zero false merges in`,
          `${d.current.counts.attached} attaches bounds the per-attach false-merge rate at **≤ ${pct(bound)} with 95%`,
          `confidence** (rule of three). A floor of ${n2(sel.rule.minAutoPrecision)} is *consistent with* that`,
          'bound, not *certified* by it — so adopting the rule\'s literal output would remove',
          'all human review on evidence that barely clears the bar it is being tested against.',
        ].join('\n')
      : '',
    '',
    `**Adopted in \`config/thresholds.json\`: \`T_auto ${n2(d.configured.tAuto)}\`** — ${
      chosen && chosen.tAuto === d.configured.tAuto
        ? 'the rule’s literal output.'
        : 'not the rule’s literal output. Basis recorded in that file:'
    }`,
    ...(chosen && chosen.tAuto === d.configured.tAuto ? [] : ['', `> ${d.configured.basis}`]),
    '',
    '### Hard floor',
    '',
    `Floor: auto-merge precision ≥ ${n2(d.floor.limit)}. Measured at the configured`,
    `thresholds: **${n3(d.floor.metric)}** — ${d.floor.passed ? 'pass, so the harness reports and exits 0' : 'FAIL, exit non-zero'}.`,
    'Per [PRODUCT open question 3](./PRODUCT.md#open-questions-for-the-plan-phase) the',
    'harness reports rather than gates in the core build; full gating is [E4](./TASKS.md#e4--ci-with-mock-mode-tests-and-evals).',
    'A degraded stage also fails the run, because a degraded stage is not a measurement.',
    '',
    END,
  ].join('\n');
}

/**
 * Replaces the generated region of the doc, or appends it if the markers are
 * not there yet. Idempotent: splicing the same block twice is a no-op, which a
 * test asserts, because a generator that drifts the file on every run would
 * make the doc's git history useless.
 */
export function spliceGenerated(doc: string, block: string): string {
  const start = doc.indexOf(BEGIN);
  const end = doc.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    return `${doc.trimEnd()}\n\n${block}\n`;
  }
  return `${doc.slice(0, start)}${block}${doc.slice(end + END.length)}`;
}

/** Console rendering of the same selection, for the terminal. */
export function renderConsole(d: ReportData): string {
  const sel = d.selection;
  const lines = [
    `provider:        ${d.provider} (${d.apiCalls} api calls, fetch disabled)`,
    `prompts:         ${Object.entries(d.promptVersions)
      .map(([k, v]) => `${k}=${v}`)
      .join(' ')}`,
    `corpus:          ${d.requests} requests, ${d.labelledProblems} labelled problems, ${d.truePairs} true pairs`,
    `degraded stages: ${Object.entries(d.degradedStages)
      .map(([k, v]) => `${k}=${v}`)
      .join(' ')}`,
    '',
    `at configured T_ask ${n2(d.configured.tAsk)} / T_auto ${n2(d.configured.tAuto)}:`,
    `  all bands   P ${n3(d.current.all.precision)}  R ${n3(d.current.all.recall)}  tp/fp/fn/tn ${cm(d.current.all)}`,
    `  auto band   P ${n3(d.current.auto.precision)}  R ${n3(d.current.auto.recall)}  tp/fp/fn/tn ${cm(d.current.auto)}`,
    `  problems    ${d.current.counts.problems} (truth ${d.labelledProblems})`,
    `  attaches    ${d.current.counts.attached} = ${d.current.counts.auto} auto + ${d.current.counts.flagged} flagged (${pct(d.current.counts.reviewLoad)} review load)`,
    `  planted     ${d.planted.grouped}/${d.planted.total} caught${d.planted.missed.length ? ` (missed ${d.planted.missed.join(', ')})` : ''}`,
    `  related     ${d.relatedPairs.merged}/${d.relatedPairs.total} wrongly merged`,
    '',
    'stage-1 recall ceiling (reported separately):',
    ...d.ceiling.map((r) => `  ${String(r.k).padStart(4)}  ${r.available}/${r.total}  ${n3(r.share)}`),
    '',
    `cosine overlap over ${d.overlap.n} labelled tuples:`,
    `  same cluster  ${n3(d.overlap.sameMin)}–${n3(d.overlap.sameMax)}`,
    `  other cluster ${n3(d.overlap.diffMin)}–${n3(d.overlap.diffMax)}`,
    `  separation    ${n3(d.overlap.separation)}  → uncontested only above ${n3(d.overlap.contestedAbove)}`,
    '',
    'sweep — T_ask  T_auto | all P/R | auto P/R | problems flagged | blind spot',
    ...d.cells
      .slice()
      .sort((a, b) => a.tAsk - b.tAsk || a.tAuto - b.tAuto)
      .map(
        (c) =>
          `       ${n2(c.tAsk)}   ${n2(c.tAuto)}  | ${n3(c.all.precision)}/${n3(c.all.recall)} ` +
          `| ${n3(c.auto.precision)}/${n3(c.auto.recall)} | ${String(c.counts.problems).padStart(8)} ${String(
            c.counts.flagged,
          ).padStart(7)} | ${c.blindSpot === 0 ? 'exact' : `${c.blindSpot} unseen`}`,
      ),
    '',
    `selection rule: lowest T_auto with auto precision >= ${n2(sel.rule.minAutoPrecision)}, then lowest T_ask with recall >= ${n2(sel.rule.minRecall)}`,
    sel.chosen
      ? `  literal output: T_ask ${n2(sel.chosen.tAsk)}  T_auto ${n2(sel.chosen.tAuto)}`
      : '  literal output: NONE — no cell clears the precision floor',
    `  precision constraint: ${sel.precisionNonBinding ? 'NON-BINDING (every cell clears it)' : 'binding'}`,
    `  recall constraint:    ${sel.recallUnsatisfiable ? `UNSATISFIABLE (best recall ${n3(sel.bestRecall)})` : 'met'}`,
    `  adopted in config:    T_auto ${n2(d.configured.tAuto)}`,
    '',
    `hard floor: auto precision ${n3(d.floor.metric)} vs >= ${n2(d.floor.limit)} — ${d.floor.passed ? 'PASS' : 'FAIL'}`,
  ];
  return lines.join('\n');
}
